// Generates the machine-readable contract from the Zod schemas.
//
// repository-structure.md §5.3 G6: "The generated JSON Schema for MCP tools
// matches the Zod validators (codegen diff must be empty)." The MCP tool
// schemas arrive in Phase 3; from Phase 1 the same mechanism covers the
// schemas and registries that already exist, so the gate is live before there
// is anything to drift.
//
// Committed output, diff-checked in CI (repository-structure.md §6). Run:
//   npm run codegen          # write
//   npm run codegen:check    # fail if the committed output is stale

import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { zodToJsonSchema } from 'zod-to-json-schema';
import type { ZodTypeAny } from 'zod';

import {
  AnswerPayloadSchema,
  AuditEventSchema,
  AuthorizationEnvelopeSchema,
  DataScopeSchema,
  LearnerQuestionDtoSchema,
  MultipleChoice4Schema,
  ProblemDetailsSchema,
  ResponsePayloadSchema,
  SessionCreationTokenSchema,
  SignedEnvelopeSchema,
  BatchResultSchema,
} from '../src/index.js';

import {
  AUDIT_ACTIONS,
  AUDIT_FAMILY_KEYS,
  ERROR_CODES,
  ERROR_REGISTRY,
  FORBIDDEN_LEARNER_RESPONSE_KEYS,
  PERMISSION_KEYS,
  QUESTION_TYPE,
  QUESTION_STATUS,
  RELEASE_1_QUESTION_TYPES,
  RELEASE_1_SOURCE_TYPES,
  ROLE_DEFINITIONS,
  SOURCE_TYPE,
} from '../src/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, '..', 'generated');

const check = process.argv.includes('--check');

const SCHEMAS: Record<string, ZodTypeAny> = {
  AuditEvent: AuditEventSchema,
  AuthorizationEnvelope: AuthorizationEnvelopeSchema,
  SignedEnvelope: SignedEnvelopeSchema,
  SessionCreationToken: SessionCreationTokenSchema,
  DataScope: DataScopeSchema,
  AnswerPayload: AnswerPayloadSchema,
  MultipleChoice4: MultipleChoice4Schema,
  ResponsePayload: ResponsePayloadSchema,
  LearnerQuestionDto: LearnerQuestionDtoSchema,
  ProblemDetails: ProblemDetailsSchema,
  BatchResult: BatchResultSchema,
};

const jsonSchemas = Object.fromEntries(
  Object.entries(SCHEMAS).map(([name, schema]) => [
    name,
    zodToJsonSchema(schema, { name, target: 'jsonSchema7', $refStrategy: 'none' }),
  ]),
);

/**
 * The registries. These are the tables other tooling and reviewers read: the
 * closed permission union, the error code table, and the audit taxonomy.
 */
const registries = {
  permissions: [...PERMISSION_KEYS].sort(),
  roles: ROLE_DEFINITIONS.map((r) => ({
    key: r.key,
    portalScope: r.portalScope,
    permissions: [...r.permissions].sort(),
  })),
  errorCodes: Object.fromEntries(
    [...ERROR_CODES].sort().map((code) => {
      const d = ERROR_REGISTRY[code];
      return [code, { category: d.category, status: d.status, retryable: d.retryable }];
    }),
  ),
  auditFamilies: [...AUDIT_FAMILY_KEYS].sort(),
  auditActions: [...AUDIT_ACTIONS].sort(),
  questionTypes: { all: [...QUESTION_TYPE], release1: [...RELEASE_1_QUESTION_TYPES] },
  questionStatuses: [...QUESTION_STATUS],
  sourceTypes: { all: [...SOURCE_TYPE], release1: [...RELEASE_1_SOURCE_TYPES] },
  forbiddenLearnerResponseKeys: [...FORBIDDEN_LEARNER_RESPONSE_KEYS].sort(),
} as const;

const artifacts: Record<string, unknown> = {
  'schemas.json': {
    $comment:
      'GENERATED by packages/shared-types/scripts/codegen.ts. Do not hand-edit; run npm run codegen.',
    schemas: jsonSchemas,
  },
  'registries.json': {
    $comment:
      'GENERATED by packages/shared-types/scripts/codegen.ts. Do not hand-edit; run npm run codegen.',
    ...registries,
  },
};

// Stable serialization: sorted keys and a trailing newline, so the diff is a
// content diff and never a key-order diff.
const stableStringify = (value: unknown): string => {
  const sortKeys = (node: unknown): unknown => {
    if (Array.isArray(node)) return node.map(sortKeys);
    if (node !== null && typeof node === 'object') {
      return Object.fromEntries(
        Object.entries(node as Record<string, unknown>)
          .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
          .map(([k, v]) => [k, sortKeys(v)]),
      );
    }
    return node;
  };
  return `${JSON.stringify(sortKeys(value), null, 2)}\n`;
};

mkdirSync(outDir, { recursive: true });

const stale: string[] = [];

for (const [fileName, content] of Object.entries(artifacts)) {
  const target = join(outDir, fileName);
  const next = stableStringify(content);

  if (check) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== next) stale.push(fileName);
  } else {
    writeFileSync(target, next, 'utf8');
    process.stdout.write(`codegen: wrote generated/${fileName}\n`);
  }
}

if (check) {
  if (stale.length > 0) {
    process.stderr.write(
      [
        'codegen: the committed output is stale.',
        ...stale.map((f) => `  - generated/${f}`),
        '',
        'A Zod schema or registry changed without regenerating the contract.',
        'Run `npm run codegen` and commit the result.',
        '',
      ].join('\n'),
    );
    process.exit(1);
  }
  process.stdout.write('codegen: committed output is up to date.\n');
}
